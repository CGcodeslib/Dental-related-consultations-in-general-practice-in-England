############### Age band and Age Group ########################################

age_band <- function(x) {
  x <- as.numeric(as.character(x))
  
  band <- dplyr::case_when(
    x < 5                     ~ "0-4",
    x >= 5  & x < 10          ~ "5-9",
    x >= 10 & x < 15          ~ "10-14",
    x >= 15 & x < 20          ~ "15-19",
    x >= 20 & x < 25          ~ "20-24",
    x >= 25 & x < 30          ~ "25-29",
    x >= 30 & x < 35          ~ "30-34",
    x >= 35 & x < 40          ~ "35-39",
    x >= 40 & x < 45          ~ "40-44",
    x >= 45 & x < 50          ~ "45-49",
    x >= 50 & x < 55          ~ "50-54",
    x >= 55 & x < 60          ~ "55-59",
    x >= 60 & x < 65          ~ "60-64",
    x >= 65 & x < 70          ~ "65-69",
    x >= 70 & x < 75          ~ "70-74",
    x >= 75 & x < 80          ~ "75-79",
    x >= 80 & x < 85          ~ "80-84",
    x >= 85 & x < 90          ~ "85-89",
    x >= 90                   ~ "90+",
    TRUE                      ~ NA_character_
  )
  
  factor(
    band,
    levels = c(
      "0-4","5-9","10-14","15-19","20-24","25-29","30-34",
      "35-39","40-44","45-49","50-54","55-59",
      "60-64","65-69","70-74","75-79","80-84","85-89","90+"
    )
  )
}

